const fs = require('node:fs')
const assert = require('node:assert/strict')
const ts = require('typescript')
const vm = require('node:vm')
const source = fs.readFileSync('src/timestamps.ts', 'utf8')
const context = { exports: {}, Intl, Date }
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context)
const format = context.exports.formatCreatedAt
const instant = '2026-10-07T15:42:00.000Z'
assert.equal(format(instant, 'en', 'UTC'), '7 October 2026, 3:42 PM')
assert.equal(format(instant, 'en', 'America/New_York'), '7 October 2026, 11:42 AM')
assert.equal(format(instant, 'en', 'Asia/Tokyo'), '8 October 2026, 12:42 AM')
assert.equal(format(instant, 'en', 'UTC'), format(instant, 'en', 'UTC'))
assert.equal(format(undefined), '—')
assert.equal(format('invalid'), '—')
for (const language of ['en','fr','es','de','pt','it','ar','zh']) assert.ok(format(instant, language, 'UTC').includes('2026') || language === 'ar')
const app = fs.readFileSync('src/App.tsx','utf8')
const client = fs.readFileSync('src/supabase.ts','utf8')
const callback = fs.readFileSync('src/authCallback.ts','utf8')
assert.ok(app.includes('if (!authReady || !authUser) return'))
assert.ok(app.includes("provider: 'google'"))
assert.ok(app.includes('supabase.auth.signInWithPassword'))
assert.ok(client.includes('persistSession: true') && client.includes('autoRefreshToken: true'))
assert.ok(callback.includes('exchangeCodeForSession(code)'))
assert.ok(callback.includes('com.minglenest.app://auth/callback'))
assert.ok(app.includes('formatCreatedAt(message.created_at, language)'))
assert.ok(app.includes('formatCreatedAt(story.createdAt, language)'))
assert.ok(app.includes("from('kids_stories').insert"))
assert.ok(!app.includes('onPaste=') && !app.includes('onCopy='))
const emojis = '😊❤️😂🔥'
assert.equal(JSON.parse(JSON.stringify({ content: emojis })).content, emojis)
assert.equal(Buffer.from(emojis, 'utf8').toString('utf8'), emojis)
console.log('Passed: date/time formatting, timezone rollover, eight locales, stable/invalid timestamps, auth/session source checks, emoji UTF-8 round-trip, and no copy/paste interception. These do not substitute for signed-in or native device tests.')
